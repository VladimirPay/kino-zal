-- Наш Кинозал — добавляет в titles число оценок на Кинопоиске (voteCount),
-- отдельно от средней оценки (kp_rating). Нужно, чтобы вкладка «Каталог»
-- могла сортировать/выбирать «популярное» по-настоящему (много кто оценил),
-- а не по случайно высокому среднему баллу у малоизвестного тайтла с горсткой
-- голосов. Используется новой функцией seedPopularCatalog (кнопка «Обновить
-- топ-подборку каталога» в разделе Управление → Фильмы) и переписанным
-- loadCatalogDefault (js/catalog.js) — они читают/пишут это поле.
--
-- Ненужно ничего дропать — только добавляет колонку и индекс, безопасно
-- выполнять повторно. Применять ПОСЛЕ social-upgrade.sql/-2/-3/-4/-5.
--
-- Supabase: SQL Editor -> New query -> вставить целиком -> Run

alter table titles add column if not exists kp_votes integer;

-- Индекс под сортировку каталога по популярности (ORDER BY kp_votes DESC).
create index if not exists titles_kp_votes_idx on titles (kp_votes desc nulls last);
